def write_csv(path, header_note, columns, rows):
    with open(path, "w", encoding="utf-8", newline="") as f:
        w = csv.writer(f)
        w.writerow([f"# {header_note}"])
        w.writerow(columns)
        for r in rows:
            w.writerow([("" if r.get(c) is None else r.get(c)) for c in columns])


