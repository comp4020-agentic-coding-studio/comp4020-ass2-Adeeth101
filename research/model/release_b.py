    weekly = sum(x[0] for x in fw) / len(fw)
    hyd = HYDRAULICS[sid]
    lift = round(hyd["fixture_rl"] - hyd["tank_outlet_rl"], 2)
    fixtures = hyd["fixtures"]
    # Ten highest one-minute flow events at the house, built from fixture signatures.
    names = [k for k in fixtures if "zone" not in k and "hose" not in k and "drip" not in k]
    events = []
    ev_rng = random.Random(7 + int(sid[1]))
    for k in range(10):
        n = 3 if k < 2 else 2
        combo = ev_rng.sample(names, n)
        peak = sum(fixtures[c] for c in combo) * ev_rng.uniform(0.9, 1.0)
        events.append({"rank": 0, "month": ISO[ev_rng.randrange(12)], "fixtures": " + ".join(combo),
                       "peak_lpm": round(peak, 1), "duration_min": ev_rng.choice([2, 3, 4, 5, 6, 8])})
    events.sort(key=lambda e: -e["peak_lpm"])
    for k, e in enumerate(events, 1):
        e["rank"] = k
    p95 = round(sorted(e["peak_lpm"] for e in events)[int(0.7 * len(events))], 1)

    zones = []
    growing = {g.id: g for g in home.cover if g.kind == "growing"}
    for zid, d in SOILS[sid].items():
        g = growing.get(zid)
        q = home.zone_quality[zid]
        zones.append({"zone": zid, "label": g.label if g else "Shared-garden allocation (common property)",
                      "area_m2": round(g.area, 1) if g else home.shared_allocation_m2,
                      "texture": d["texture"], "ph_water": d["ph"], "ec_ds_m": d["ec"],
                      "organic_carbon_pct": d["oc"], "nitrate_n_mg_kg": d["no3"], "colwell_p_mg_kg": d["p"],
                      "rooting_depth_cm": d["depth"], "sun_hours_summer": d["sun_s"], "sun_hours_winter": d["sun_w"],
                      "relative_productivity": q,
                      "productivity_class": "A" if q >= 0.9 else "B" if q >= 0.75 else "C" if q >= 0.6 else "D",
                      "note": d["note"]})

    quality = []
    for i, src, turb, ecoli, hard, tds, ph, fe, note in QUALITY[sid]:
        quality.append({"month": ISO[i], "source": src, "turbidity_ntu": turb, "e_coli_mpn_100ml": ecoli,
                        "hardness_mg_l_caco3": hard, "tds_mg_l": tds, "ph": ph, "iron_mg_l": fe, "note": note})

    harvest = round(r["fresh_kg"])
    summary = {
        "rain_mm": round(sum(x["rain_mm"] for x in months)),
        "rain_mean_mm": round(sum(sc.mean_climate(sid).rain)),
        "roof_inflow_kl": round(sum(x["roof_inflow_kl"] for x in months), 1),
        "overflow_kl": round(sum(x["overflow_kl"] for x in months), 1),
        "indoor_kl": round(sum(x["indoor_kl"] for x in months), 1),
        "indoor_l_person_day": round(sum(x["indoor_kl"] for x in months) * 1000 / 4 / 366, 1),
        "imported_kl": round(sum(x["imported_kl"] for x in months), 1),
        "bore_kl": round(sum(x["bore_kl"] for x in months), 1),
        "garden_applied_kl": round(sum(x["garden_applied_kl"] for x in months), 1),
        "garden_unmet_kl": round(sum(x["garden_unmet_estimate_kl"] for x in months), 1),
        "pump_kwh": round(sum(x["pump_kwh"] for x in months)),
        "runoff_coefficient": round(runoff_coeff, 2) if runoff_coeff else None,
        "connected_roof_m2": connected,
        "harvest_kg": harvest,
        "food_waste_kg_week": round(weekly, 1),
        "food_waste_kg_year": round(weekly * 52),
        "plant_share": round(sum(x[1] for x in fw) / sum(x[0] for x in fw), 2),
        "frost_nights": sum(x["frost_nights"] for x in months),
        "static_lift_m": lift,
        "peak_flow_lpm": events[0]["peak_lpm"],
        "p70_event_lpm": p95,
        "months_empty": sum(1 for x in months if x["tank_end_kl"] < 0.5),
    }
    need = sum(x["garden_applied_kl"] + x["garden_unmet_estimate_kl"] for x in months)
    pshare = round(100 * sum(x["garden_applied_kl"] for x in months) / need) if need else 100
    full = ["April", "May", "June", "July", "August", "September", "October", "November", "December",
            "January", "February", "March"]

    def run_text(flags):
        """Name the months flagged, as one circular run where possible."""
        idx = [i for i in range(12) if flags[i]]
        if not idx:
            return "no month"
        if len(idx) == 12:
            return "every month"
        start = next(i for i in range(12) if flags[i] and not flags[i - 1])
        run = []
        i = start
        while flags[i % 12] and len(run) < 12:
            run.append(i % 12)
            i += 1
        if len(run) == len(idx):
            if len(run) == 1:
                return full[run[0]]
            if len(run) == 2:
                return f"{full[run[0]]} and {full[run[1]]}"
            return f"every month from {full[run[0]]} to {full[run[-1]]}"
        return ", ".join(full[i] for i in idx[:-1]) + " and " + full[idx[-1]]
    implications = [t.format(frost=summary["frost_nights"], loads=math.ceil(summary["imported_kl"] / 12),
                             pshare=pshare,
                             empty_run=run_text([x["tank_end_kl"] < 0.5 for x in months]),
                             over_kl=round(summary["overflow_kl"]),
                             over_run=run_text([x["overflow_kl"] > 0.5 for x in months]),
                             cart_run=run_text([x["imported_kl"] > 0.5 for x in months]))
                    for t in IMPLICATIONS[sid]]
    return {
        "sid": sid, "slug": home.slug, "short": home.short, "family": home.family,
        "memo_date": MEMO_DATE, "year": YEAR_LABEL, "team": TEAM,
        "months": months, "summary": summary, "events": events, "zones": zones,
        "quality": quality, "food_waste": [{"week": AUDIT_WEEKS[k], "total_kg": a, "plant_kg": b,
                                             "meat_dairy_kg": c, "garden_kg": d} for k, (a, b, c, d) in enumerate(fw)],
        "hydraulics": {"tank_outlet_rl": hyd["tank_outlet_rl"], "highest_fixture": hyd["fixture"],
                       "highest_fixture_rl": hyd["fixture_rl"], "garden_high_rl": hyd["garden_high_rl"],
                       "static_lift_m": lift, "fixtures_lpm": fixtures, "served_now": hyd["served_now"],
                       "note": hyd["pressure_note"]},
        "costs": COSTS[sid], "implications": implications, "questions": QUESTIONS[sid],
        "missing": [{"month": ISO[i], "field": f_, "note": n} for i, f_, n in MISSING[sid]],
    }


